"""Checks that the web page has the parts we promised (written by Rabia, the lead).

These are the basics only. The full usability check is the manual checklist in docs/tasks/KAINAT.md.
The ids matter: the real integration code and the final demo script look for these exact names.

Run:   pytest app/tests/test_gui_elements.py -q
Do NOT edit this file to make a test pass. If you think a test is wrong, message Rabia.
"""
import re
from pathlib import Path

import pytest

HTML = (Path(__file__).resolve().parents[1] / "static" / "index.html").read_text(encoding="utf-8")

REQUIRED_IDS = {
    "video": "the live camera image",
    "sign": "the current sign name",
    "confidence-bar": "the confidence bar",
    "confidence-text": "the confidence as a number",
    "sentence": "the sentence being built",
    "suggestions": "the suggestion buttons area",
    "history": "the list of finished sentences",
    "status": "the system status message (hand detected, not sure, connected...)",
    "btn-speak": "the Speak button",
    "btn-undo": "the Undo button",
    "btn-clear": "the Clear button",
    "btn-camera": "the Start/Stop camera button",
}


@pytest.mark.parametrize("element_id", sorted(REQUIRED_IDS))
def test_required_element_exists(element_id):
    assert re.search(rf"""id\s*=\s*["']{re.escape(element_id)}["']""", HTML), \
        f'missing id="{element_id}": {REQUIRED_IDS[element_id]}'


def test_html_declares_language():
    assert re.search(r"<html[^>]*\blang\s*=", HTML, re.I), '<html> needs a lang attribute, e.g. lang="en"'


def test_page_has_a_title():
    assert re.search(r"<title>\s*\S+", HTML, re.I), "the page needs a non-empty <title>"


def test_page_is_mobile_friendly():
    assert re.search(r'<meta[^>]*name\s*=\s*["\']viewport["\']', HTML, re.I), "add the viewport meta tag"


def test_sentence_is_announced_to_screen_readers():
    assert "aria-live" in HTML, 'the sentence area needs aria-live="polite" so screen readers announce changes'


def test_camera_image_has_alt_text():
    img = re.search(r"<img[^>]*>", HTML, re.I)
    assert img and re.search(r'\balt\s*=\s*["\'][^"\']+["\']', img.group(0)), "the camera <img> needs a meaningful alt text"


def test_dark_mode_supported():
    assert "prefers-color-scheme" in HTML, "add a @media (prefers-color-scheme: dark) section"


def test_buttons_have_visible_text_or_label():
    for m in re.finditer(r"<button([^>]*)>(.*?)</button>", HTML, re.I | re.S):
        text = re.sub(r"<[^>]+>", "", m.group(2)).strip()
        assert text or "aria-label" in m.group(1), "every <button> needs visible text or an aria-label"
