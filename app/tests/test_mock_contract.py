"""Acceptance tests for the website's data (written by Rabia, the lead).

The mock stream (app/mock/fake_stream.py) pretends to be the real vision + context parts.
The real parts will send EXACTLY the same shapes, so if the mock is correct, the website
will keep working when we swap the fakes for the real thing.

Run:   pytest app/tests/test_mock_contract.py -q
Do NOT edit this file to make a test pass. If you think a test is wrong, message Rabia.
"""
import asyncio

import pytest

from common.validators import validate_context_output, validate_prediction


@pytest.fixture
def items(monkeypatch):
    """Collect the first 12 messages from the mock stream, without waiting between them."""
    from app.mock.fake_stream import fake_stream

    async def no_wait(_seconds):
        return None

    monkeypatch.setattr(asyncio, "sleep", no_wait)

    async def take(n):
        got = []
        async for item in fake_stream():
            got.append(item)
            if len(got) == n:
                break
        return got

    return asyncio.run(take(12))


def test_every_message_has_prediction_and_context(items):
    for item in items:
        assert "prediction" in item and "context" in item


def test_predictions_follow_contract_1(items):
    for item in items:
        validate_prediction(item["prediction"])


def test_context_follows_contract_2(items):
    for item in items:
        validate_context_output(item["context"])


def test_mock_shows_a_low_confidence_case(items):
    """The page must be able to show 'Not sure, did you mean...?', so the mock needs such a case."""
    assert any(i["prediction"]["confidence"] < 0.6 for i in items)


def test_mock_shows_a_high_confidence_case(items):
    assert any(i["prediction"]["confidence"] >= 0.85 for i in items)


def test_mock_uses_at_least_six_different_signs(items):
    assert len({i["prediction"]["sign"] for i in items}) >= 6


def test_mock_sentence_grows_and_changes(items):
    assert len({i["context"]["sentence"] for i in items}) >= 4


def test_mock_sometimes_has_suggestions_and_sometimes_not(items):
    sizes = {len(i["context"]["suggestions"]) for i in items}
    assert 0 in sizes and any(n > 0 for n in sizes)


def test_websocket_endpoint_sends_the_same_shape():
    """Starts the real web app in memory and reads 2 messages from /ws (needs: pip install httpx)."""
    pytest.importorskip("httpx")
    from fastapi.testclient import TestClient
    from app.main import app

    with TestClient(app) as client:
        with client.websocket_connect("/ws") as ws:
            for _ in range(2):
                msg = ws.receive_json()
                validate_prediction(msg["prediction"])
                validate_context_output(msg["context"])
