import itertools

import pytest

from common.contracts import make_prediction
from common.validators import validate_context_output
from common.vocabulary import LABELS
from context.sentence_builder import SentenceBuilder


def pred(sign, conf=0.9, t=0.0):
    return make_prediction(sign, conf, [(sign, conf)], t)


def feed(builder, signs, conf=0.9, step=1.0):
    """Send signs one by one, one second apart. Returns the last output."""
    out = None
    for i, s in enumerate(signs):
        out = builder.add(pred(s, conf, i * step))
    return out


# ---------------------------------------------------------------- contract
def test_contract_output_shape_at_every_step():
    b = SentenceBuilder()
    validate_context_output(b.output())
    for i, s in enumerate(["me", "want", "water"]):
        validate_context_output(b.add(pred(s, 0.9, i)))


def test_contract_raw_signs_lists_accepted_words():
    b = SentenceBuilder()
    out = feed(b, ["me", "want", "water"])
    assert out["raw_signs"] == ["me", "want", "water"]


# ------------------------------------------------------------------ grammar
SENTENCES = [
    (["me", "want", "water"], "I want water."),
    (["me", "need", "water"], "I need water."),
    (["me", "need", "help"], "I need help."),
    (["me", "want", "eat"], "I want to eat."),
    (["me", "want", "drink"], "I want to drink."),
    (["me", "want", "go", "home"], "I want to go home."),
    (["me", "go", "home"], "I am going home."),
    (["where", "bathroom"], "Where is the bathroom?"),
    (["you", "want", "water"], "Do you want water?"),
    (["you", "need", "help"], "Do you need help?"),
    (["you", "eat"], "Did you eat?"),
    (["you", "go", "home"], "Are you going home?"),
    (["please", "help"], "Please help."),
    (["water", "please"], "Water, please."),
    (["hello"], "Hello!"),
    (["bye"], "Goodbye!"),
    (["thankyou"], "Thank you!"),
    (["what"], "What?"),
    (["hello", "me", "need", "help"], "Hello! I need help."),
    (["me", "need", "help", "thankyou"], "I need help. Thank you!"),
    (["sorry", "me", "go", "home"], "Sorry. I am going home."),
    (["yes", "me", "want", "water"], "Yes. I want water."),
    (["water", "home"], "Water home."),          # no rule for this: fall back to the words joined
]


@pytest.mark.parametrize("signs,expected", SENTENCES, ids=[" ".join(s) for s, _ in SENTENCES])
def test_grammar_sentences(signs, expected):
    assert feed(SentenceBuilder(), signs)["sentence"] == expected


def test_grammar_never_crashes_and_always_gives_punctuated_text():
    """Every possible sequence of 1 to 3 signs must give a sensible, non-empty sentence."""
    for n in (1, 2, 3):
        for combo in itertools.product(LABELS, repeat=n):
            sentence = feed(SentenceBuilder(), list(combo))["sentence"]
            assert sentence, f"empty sentence for {combo}"
            assert sentence[-1] in ".!?", f"no ending punctuation for {combo}: {sentence!r}"
            assert sentence[0].isupper(), f"sentence should start with a capital for {combo}: {sentence!r}"


# ---------------------------------------------------------------- filtering
def test_filtering_weak_guess_is_ignored():
    b = SentenceBuilder()
    b.add(pred("me", 0.2))
    assert b.words == []


def test_filtering_exact_min_conf_is_accepted():
    b = SentenceBuilder(min_conf=0.6)
    b.add(pred("water", 0.6))
    assert b.words == ["water"]


def test_filtering_immediate_repeat_is_ignored():
    b = SentenceBuilder()
    feed(b, ["water", "water"])
    assert b.words == ["water"]


def test_filtering_same_sign_later_is_allowed():
    b = SentenceBuilder()
    feed(b, ["yes", "water", "yes"])
    assert b.words == ["yes", "water", "yes"]


def test_filtering_custom_min_conf():
    b = SentenceBuilder(min_conf=0.8)
    b.add(pred("bye", 0.7))          # 'bye' does not fit the start of a sentence, so no rescue
    assert b.words == []


# ------------------------------------------------------- context (the smart part)
def test_rescue_weak_guess_accepted_when_it_fits_the_context():
    b = SentenceBuilder()
    feed(b, ["me", "want"])
    b.add(pred("drink", 0.45, 2))     # below 0.6 but 'drink' is a likely next word after 'me want'
    assert b.words == ["me", "want", "drink"]


def test_rescue_weak_guess_rejected_when_it_does_not_fit():
    b = SentenceBuilder()
    feed(b, ["me", "want"])
    b.add(pred("bye", 0.45, 2))
    assert b.words == ["me", "want"]


def test_rescue_very_weak_guess_is_always_rejected():
    b = SentenceBuilder()
    feed(b, ["me", "want"])
    b.add(pred("drink", 0.30, 2))     # below rescue_conf (0.35)
    assert b.words == ["me", "want"]


# -------------------------------------------------------------- suggestions
def test_suggestions_at_the_start():
    assert "me" in SentenceBuilder().output()["suggestions"]


def test_suggestions_after_me():
    s = feed(SentenceBuilder(), ["me"])["suggestions"]
    assert "want" in s and "need" in s


def test_suggestions_after_me_want():
    s = feed(SentenceBuilder(), ["me", "want"])["suggestions"]
    assert {"water", "eat", "drink"} <= set(s)


def test_suggestions_after_where():
    s = feed(SentenceBuilder(), ["where"])["suggestions"]
    assert "bathroom" in s and "home" in s


def test_suggestions_after_hello():
    assert "me" in feed(SentenceBuilder(), ["hello"])["suggestions"]


def test_suggestions_are_valid_short_and_never_repeat_the_last_word():
    for combo in itertools.product(LABELS, repeat=2):
        out = feed(SentenceBuilder(), list(combo))
        validate_context_output(out)
        assert out["raw_signs"][-1] not in out["suggestions"]


# -------------------------------------------------- pause = sentence finished
def test_pause_long_gap_finishes_the_sentence():
    b = SentenceBuilder()
    b.add(pred("me", 0.9, 0))
    b.add(pred("want", 0.9, 1))
    b.add(pred("water", 0.9, 2))
    out = b.add(pred("hello", 0.9, 10))      # 8 seconds later: new sentence
    assert b.history == ["I want water."]
    assert out["sentence"] == "Hello!"
    assert b.words == ["hello"]


def test_pause_short_gaps_do_not_split():
    b = SentenceBuilder()
    b.add(pred("me", 0.9, 0))
    b.add(pred("want", 0.9, 2))
    out = b.add(pred("water", 0.9, 4))
    assert out["sentence"] == "I want water."
    assert b.history == []


def test_pause_finish_returns_sentence_and_resets():
    b = SentenceBuilder()
    feed(b, ["me", "want", "water"])
    assert b.finish() == "I want water."
    assert b.output()["sentence"] == ""
    assert b.words == []
    assert b.history == ["I want water."]


def test_pause_finish_on_empty_does_nothing():
    b = SentenceBuilder()
    assert b.finish() == ""
    assert b.history == []


# -------------------------------------------------------------- undo / clear
def test_undo_removes_last_word():
    b = SentenceBuilder()
    feed(b, ["me", "want", "water"])
    out = b.undo()
    assert out["raw_signs"] == ["me", "want"]


def test_undo_on_empty_is_safe():
    out = SentenceBuilder().undo()
    assert out["raw_signs"] == [] and out["sentence"] == ""


def test_clear_resets_words_but_keeps_history():
    b = SentenceBuilder()
    feed(b, ["me", "want", "water"])
    b.finish()
    feed(b, ["hello"])
    out = b.clear()
    assert out["raw_signs"] == [] and out["sentence"] == ""
    assert b.history == ["I want water."]
